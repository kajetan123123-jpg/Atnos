from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from atnos.core.config import Settings
from atnos.production.models import ProductionContext


def write_production_log(settings: Settings, context: ProductionContext) -> Path | None:
    vault = settings.obsidian_vault_path
    if not settings.obsidian_export_enabled or not settings.atnos_write_obsidian_logs:
        return None
    if vault is None or not vault.exists() or not vault.is_dir():
        return None
    vault_root = vault.resolve()
    shorts_dir = (vault_root / settings.atnos_obsidian_shorts_dir.strip()).resolve()
    if not _is_inside(shorts_dir, vault_root):
        return None
    target_dir = (shorts_dir / _slug(context.account_id)).resolve()
    if not _is_inside(target_dir, vault_root):
        return None
    qa = context.artifacts.get("qa", {})
    hook = context.artifacts.get("hook", {}).get("selected", {})
    target_dir.mkdir(parents=True, exist_ok=True)
    title = context.topic.title
    path = target_dir / f"{context.job_id}-{_slug(title)}.md"
    blocking = qa.get("blocking_failures") or []
    warnings = qa.get("warnings") or []
    content = f"""---
type: production-log
account_id: {context.account_id}
job_id: {context.job_id}
date: {qa.get("timestamp", "")}
status: {context.artifacts.get("final_status", "qa_pending")}
score: {context.topic.total_score}
---

# {title}

## Hook used
{hook.get("text", "")}

## QA Result
- Overall: {qa.get("overall", "unknown")}
- Blocking: {", ".join(blocking) if blocking else "none"}
- Warnings: {", ".join(warnings) if warnings else "none"}

## Performance (fill after 48h)
- Views:
- CTR:
- Avg view %:

## Notes
Generated by Atnos production pipeline. Review QA before scheduling public release.
"""
    path.write_text(content, encoding="utf-8")
    return path


def write_analytics_learning_note(
    settings: Settings,
    *,
    account_id: str,
    topic_id: str,
    youtube_video_id: str,
    window_hours: int,
    analytics: dict[str, Any],
    score_update: dict[str, Any],
    completed_at: str,
) -> Path | None:
    """Persist post-upload analytics learning into Obsidian for future style-guide reads."""
    vault = settings.obsidian_vault_path
    if not settings.obsidian_export_enabled or not settings.atnos_write_obsidian_logs:
        return None
    if vault is None or not vault.exists() or not vault.is_dir():
        return None
    vault_root = vault.resolve()
    target_dir = (vault_root / settings.atnos_obsidian_shorts_dir.strip()).resolve()
    if not _is_inside(target_dir, vault_root):
        return None
    safe_account = _slug(account_id)
    target_dir.mkdir(parents=True, exist_ok=True)
    stamp = completed_at.replace(":", "").replace("+", "-").replace(".", "-")
    path = target_dir / f"channel-learning-{safe_account}-{stamp}.md"
    performance_score = score_update.get("performance_score")
    recommendation = score_update.get("recommendation") or "Brak rekomendacji."
    qa_summary = score_update.get("qa_summary")
    qa_learning_section = _format_qa_learning_section(qa_summary if isinstance(qa_summary, dict) else {})
    content = f"""---
type: channel-learning
account_id: {account_id}
topic_id: {topic_id}
youtube_video_id: {youtube_video_id}
window_hours: {window_hours}
date: {completed_at}
performance_score: {performance_score}
---

# Channel Learning: {account_id}

## Wynik po {window_hours}h
- Video ID: {youtube_video_id}
- Views: {analytics.get("views", "unknown")}
- Average view %: {analytics.get("average_view_percentage", "unknown")}
- Average view duration: {analytics.get("average_view_duration", "unknown")}
- Likes: {analytics.get("likes", "unknown")}
- Comments: {analytics.get("comments", "unknown")}
- Shares: {analytics.get("shares", "unknown")}
- Subscribers gained: {analytics.get("subscribers_gained", "unknown")}
- Performance score: {performance_score}

## Lekcja dla kolejnych shortów
{recommendation}

{qa_learning_section}

## Score breakdown
- Views score: {score_update.get("views_score", "unknown")}
- Retention score: {score_update.get("retention_score", "unknown")}
- Duration score: {score_update.get("duration_score", "unknown")}
- Engagement score: {score_update.get("engagement_score", "unknown")}
- Subscriber score: {score_update.get("subscriber_score", "unknown")}

## Instrukcja dla Atnosa
Użyj tej lekcji jako kontekstu przy następnym Hook Generator, Script Generator i Asset Planner.
Nie traktuj tych danych jako gwarancji zarobków ani przyszłych wyników.
"""
    path.write_text(content, encoding="utf-8")
    return path


def _slug(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9_-]+", "-", value.strip().lower()).strip("-")
    return normalized[:80] or "production"


def _format_qa_learning_section(qa_summary: dict[str, Any]) -> str:
    if not qa_summary:
        return """## QA przed uploadem
- Status QA: unknown
- Upload decision: unknown
- Private upload allowed: unknown
- Auto uploadable: unknown
- Blocking failures: none
- Advisory failures: none"""

    blocking = qa_summary.get("blocking_failures") or []
    advisory = qa_summary.get("advisory_failures") or []
    return f"""## QA przed uploadem
- Status QA: {qa_summary.get("overall", "unknown")}
- Upload decision: {qa_summary.get("upload_decision_status", "unknown")}
- Private upload allowed: {_format_bool(qa_summary.get("private_upload_allowed"))}
- Auto uploadable: {_format_bool(qa_summary.get("auto_uploadable"))}
- Blocking failures: {", ".join(map(str, blocking)) if blocking else "none"}
- Advisory failures: {", ".join(map(str, advisory)) if advisory else "none"}"""


def _format_bool(value: Any) -> str:
    if value is True:
        return "true"
    if value is False:
        return "false"
    return "unknown"


def _is_inside(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False
